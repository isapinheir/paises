def menu():
    while True:
        print("")
        print("1. Buscar sigla")
        print("2. Listar siglas")
        print("0. Encerrar programa")
        
        opt = input()

        match opt:
            case '1':                    
                print("Digite o país desejado. Para inserir mais de um país, use ponto e vírgula.")
                print("==> ", end="")
                texto = input().title().replace(" ", "")
                print("")
                ler(texto)
            case '2':
                listar()
            case '0':
                break
            case _:
                print("Opção inválida.")
        

def ler(t):
        t = t.split(";")

        for p in t:
            if(p in paises):
                print(Fore.BLUE, "País:", Style.RESET_ALL, p, Fore.BLUE, "Sigla: ", Style.RESET_ALL, paises.get(p))
            else:
                print("Código não identificado para o país ", Fore.BLUE, p, Style.RESET_ALL)

def listar():
    for k, v in paises.items():
        print(Fore.BLUE, "País:", Style.RESET_ALL, k, Fore.BLUE, "Sigla: ", Style.RESET_ALL, v)

